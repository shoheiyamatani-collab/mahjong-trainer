const enforcedPolicy = [
  "base-uri 'self'",
  "object-src 'none'",
  "frame-ancestors 'self'",
  "form-action 'self'"
].join("; ");

// Stage the resource allowlist without blocking AdSense or Next's static inline
// scripts. No violation reports are sent to an external service.
const monitoredPolicy = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' https://*.googlesyndication.com https://*.doubleclick.net https://*.google.com https://*.googletagmanager.com https://*.cloudflareinsights.com",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "img-src 'self' data: blob: https:",
  "font-src 'self' data: https://fonts.gstatic.com",
  "connect-src 'self' https://*.googlesyndication.com https://*.doubleclick.net https://*.google.com https://*.google-analytics.com https://*.googletagmanager.com https://*.cloudflareinsights.com",
  "frame-src 'self' https://www.youtube-nocookie.com https://www.youtube.com https://*.googlesyndication.com https://*.doubleclick.net https://*.google.com",
  "worker-src 'self' blob:",
  "media-src 'self' blob:",
  "manifest-src 'self'"
].join("; ");

export const securityHeaders = Object.freeze({
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "X-Frame-Options": "SAMEORIGIN",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
  "Content-Security-Policy": enforcedPolicy,
  "Content-Security-Policy-Report-Only": monitoredPolicy
});

export function renderCloudflareHeaders() {
  return [
    "# Generated by apps/web/scripts/generate-video-seo-headers.mjs.",
    "# SEO indexing stays in packages/content-index-policy and Metadata API.",
    "/*",
    ...Object.entries(securityHeaders).map(([name, value]) => `  ${name}: ${value}`),
    // Limit HSTS to the production hostname; do not cover unrelated subdomains
    // or opt into the preload list.
    "https://jongfolio.com/*",
    "  Strict-Transport-Security: max-age=15552000",
    ""
  ].join("\n");
}
